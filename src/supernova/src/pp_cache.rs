//! On-disk cache for the SuperNova public parameters.
//!
//! `PublicParams::setup` synthesises every circuit shape and derives the
//! commitment keys. None of that depends on the witness, so the result can be
//! written once and read back on every later run (arecibo derives serde for
//! `PublicParams`; bincode round-trips it byte for byte, minus the digest
//! `OnceCell`, which is recomputed lazily).
//!
//! What the file cannot know is whether the circuit code that produced it is
//! the code now running. The bytes deserialise against any `C1` — the type is
//! a `PhantomData` — and the R1CS matrices inside are simply the ones that
//! were true when the file was written. The tests below pin down what happens
//! when they no longer are: nothing in the construction hashes the *source*,
//! so pc binding and the pp digest both faithfully attest to the *stale*
//! matrices.

use std::path::Path;

use crate::prelude::*;

/// Public parameters for our engine pair and trivial secondary, generic in
/// the primary step-circuit type.
pub type Params<C1> = PublicParams<E1, E2, C1, Secondary>;

/// Where [`load_or_setup`] got its parameters from.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Source {
    /// Deserialised from the cache file.
    Cache,
    /// Freshly generated by `PublicParams::setup` (and written to the cache).
    Setup,
}

/// Deserialise parameters from `path`.
pub fn read<C1: StepCircuit<F>>(path: &Path) -> Result<Params<C1>, Box<dyn std::error::Error>> {
    let bytes = std::fs::read(path)?;
    Ok(bincode::deserialize(&bytes)?)
}

/// Serialise `pp` to `path`, creating parent directories. Returns the byte count.
pub fn write<C1: StepCircuit<F>>(path: &Path, pp: &Params<C1>) -> std::io::Result<usize> {
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir)?;
    }
    let bytes = bincode::serialize(pp).map_err(std::io::Error::other)?;
    std::fs::write(path, &bytes)?;
    Ok(bytes.len())
}

/// Parameters from `path` if it holds any, else from `setup` — which are then
/// written to `path` for next time. A cache write failure is reported and
/// ignored: the parameters in hand are correct either way.
///
/// The caller owns the cache key. Nothing here checks that the file matches
/// `circuit`: see the `stale_cache_*` tests for exactly how a mismatch shows
/// up, and delete the file after changing circuit code.
pub fn load_or_setup<C1, NC>(path: &Path, circuit: &NC) -> (Params<C1>, Source)
where
    C1: StepCircuit<F>,
    NC: NonUniformCircuit<E1, E2, C1, Secondary>,
{
    if path.exists() {
        match read(path) {
            Ok(pp) => return (pp, Source::Cache),
            Err(e) => eprintln!(
                "cached public params at {} unreadable ({e}), regenerating",
                path.display()
            ),
        }
    }

    let pp = Params::<C1>::setup(circuit, &*default_ck_hint(), &*default_ck_hint());
    if let Err(e) = write(path, &pp) {
        eprintln!("could not cache public params at {}: {e}", path.display());
    }
    (pp, Source::Setup)
}

/// A short hex fingerprint of the step circuits' R1CS: every circuit index
/// is synthesized once into a `TestConstraintSystem` and its constraint
/// hash folded in. It changes whenever a circuit's constraints change, in
/// count *or* in coefficient, and whenever the frame geometry does, which
/// is exactly when a cached `PublicParams` stops matching. Put it in the
/// cache file name and a stale file is simply never found.
///
/// arecibo's augmented wrapper around the step circuits is not covered;
/// that only moves with the arecibo version.
pub fn fingerprint<C1, NC>(circuit: &NC) -> String
where
    C1: StepCircuit<F>,
    NC: NonUniformCircuit<E1, E2, C1, Secondary>,
{
    use bellpepper_core::test_cs::TestConstraintSystem;
    use std::hash::{DefaultHasher, Hash, Hasher};

    let mut hasher = DefaultHasher::new();
    for i in 0..circuit.num_circuits() {
        let step = circuit.primary_circuit(i);
        let mut cs = TestConstraintSystem::<F>::new();
        let z: Vec<AllocatedNum<F>> = (0..step.arity())
            .map(|j| AllocatedNum::alloc_input(cs.namespace(|| format!("z{j}")), || Ok(F::ZERO)).unwrap())
            .collect();
        let pc = AllocatedNum::alloc_input(cs.namespace(|| "pc"), || Ok(F::ZERO)).unwrap();
        step.synthesize(&mut cs.namespace(|| "F"), Some(&pc), &z)
            .expect("shape synthesis of a step circuit failed");
        cs.hash().hash(&mut hasher);
    }
    format!("{:016x}", hasher.finish())
}

// ---------------------------------------------------------------------------
// Staleness: what a cache file from an older build does to a newer one.
//
// The scenario is always the same. "Yesterday" the binary ran `setup` for the
// shipped circuits and wrote the file. "Today" the gain circuit has been
// edited, the binary rebuilt, the file forgotten. `Evolved` stands in for
// today's `ProgramSteps`: it delegates to the real circuits and then applies
// one of three small, realistic edits to the gain step only, so the base step
// (DPC) still goes through and the damage lands mid-schedule, at the DPC ->
// gain handover, as it would in main.
//
// The three edits cover the three shapes an edit can take, and get three
// different outcomes:
//
//   edit                  vars   cons   prove              verify (stale pp)
//   new variable           +1     +1    InvalidWitnessLength at the first gain step
//   new constraint          =     +1    ok                 ok — proves YESTERDAY's circuit
//   changed coefficient     =      =    ok                 UnSatIndex("r_primary", _)
//
// The middle row is the one to remember: no error anywhere, and the proof is
// for a circuit that no longer exists in the source tree.
//
// Nor does a verifier holding today's parameters catch it the way one would
// hope. arecibo 0.1.1's `supernova::RecursiveSNARK::verify` absorbs the
// digest stored *in the proof* (`self.pp_digest`, supernova/mod.rs:883), not
// `pp.digest()` of the parameters it was handed, so the hash chain checks
// out against any parameters and the mismatch only surfaces in the R1CS
// satisfiability pass — as an `assert_eq!` panic on the error-vector length
// when the constraint count moved (r1cs/mod.rs:255). Plain Nova
// (lib.rs:626) and SuperNova's `CompressedSNARK::verify` (snark.rs:253) do
// absorb `pp.digest()`: the digest binds parameters at the compressed level,
// not at the recursive one. pc binding is orthogonal to all of this — it
// says which of the cached shapes ran at each step, not whether the cached
// shapes are current.
// ---------------------------------------------------------------------------
#[cfg(test)]
mod tests {
    use super::*;
    use crate::circuits::spectra::{ProgramSteps, SPECTRA};
    use arecibo::errors::NovaError;
    use arecibo::supernova::error::SuperNovaError;
    use std::path::PathBuf;

    const W: usize = 8;
    const H: usize = 2;
    const GAIN: u8 = 2;
    const R_GAIN: u8 = 2;
    const B_GAIN: u8 = 4;

    /// Which later edit to the gain circuit today's build carries.
    #[derive(Clone, Copy, Debug, PartialEq, Eq)]
    enum Edit {
        /// The shipped circuit, untouched: `Evolved` is then exactly `ProgramSteps`.
        None,
        /// A new constraint over variables that already exist (`h * 1 = h`):
        /// the matrices grow by a row, the witness does not.
        NewConstraint,
        /// A new gadget variable `t` with `t * k = h`: one more variable, one
        /// more constraint, and the coefficient `k` baked into the B matrix.
        Scaled(u64),
    }

    /// `ProgramSteps` as a later commit would compile it.
    #[derive(Clone)]
    struct Evolved {
        inner: ProgramSteps,
        edit: Edit,
    }

    impl StepCircuit<F> for Evolved {
        fn arity(&self) -> usize {
            self.inner.arity()
        }

        fn circuit_index(&self) -> usize {
            self.inner.circuit_index()
        }

        fn synthesize<CS: ConstraintSystem<F>>(
            &self,
            cs: &mut CS,
            pc: Option<&AllocatedNum<F>>,
            z: &[AllocatedNum<F>],
        ) -> Result<(Option<AllocatedNum<F>>, Vec<AllocatedNum<F>>), SynthesisError> {
            let (pc_next, z_next) = self.inner.synthesize(cs, pc, z)?;
            if !matches!(self.inner, ProgramSteps::Gain(_)) {
                return Ok((pc_next, z_next));
            }
            // H_IN_GAIN after this row: a Poseidon output, so never zero, so
            // `t * 2 = h` and `t * 1 = h` really do disagree on every step.
            let h = &z_next[2];
            match self.edit {
                Edit::None => {}
                Edit::NewConstraint => cs.enforce(
                    || "evolved: h * 1 = h",
                    |lc| lc + h.get_variable(),
                    |lc| lc + CS::one(),
                    |lc| lc + h.get_variable(),
                ),
                Edit::Scaled(k) => {
                    let k_f = F::from(k);
                    let t = AllocatedNum::alloc(cs.namespace(|| "evolved: t"), || {
                        let h = h.get_value().ok_or(SynthesisError::AssignmentMissing)?;
                        Ok(h * k_f.invert().unwrap())
                    })?;
                    cs.enforce(
                        || "evolved: t * k = h",
                        |lc| lc + t.get_variable(),
                        |lc| lc + (k_f, CS::one()),
                        |lc| lc + h.get_variable(),
                    );
                }
            }
            Ok((pc_next, z_next))
        }
    }

    /// Today's program: the real `SPECTRA` schedule, gain step edited.
    struct Program {
        base: SPECTRA,
        edit: Edit,
    }

    impl NonUniformCircuit<E1, E2, Evolved, Secondary> for Program {
        fn num_circuits(&self) -> usize {
            INDECES.len()
        }
        fn primary_circuit(&self, circuit_index: usize) -> Evolved {
            Evolved { inner: self.base.primary_circuit(circuit_index), edit: self.edit }
        }
        fn secondary_circuit(&self) -> Secondary {
            Default::default()
        }
    }

    impl Program {
        fn step(&self, k: usize) -> Evolved {
            Evolved { inner: self.base.step(k), edit: self.edit }
        }
        fn num_steps(&self) -> usize {
            self.base.num_steps()
        }
    }

    /// An all-zero frame is honest advice for every stage with no reference
    /// implementation in the loop: an empty mask passes 0 through DPC, 0
    /// gains to 0 under any factor, a zero band demosaics to zero planes,
    /// and zero planes white-balance to zero planes.
    fn program(edit: Edit) -> Program {
        let zeros = || vec![vec![0u8; W]; H];
        let base = SPECTRA::new(
            GAIN,
            vec![vec![false; W]; H],
            W,
            H,
            zeros(),
            zeros(),
            zeros(),
            zeros(),
            zeros(),
            zeros(),
            R_GAIN,
            B_GAIN,
            zeros(),
            zeros(),
        );
        Program { base, edit }
    }

    /// z_0 for the all-zero program: parameters and the empty mask's digest.
    fn z0() -> Vec<F> {
        let mask = vec![vec![false; W]; H];
        let spec = crate::evidence::Spec { gain: GAIN, r_gain: R_GAIN, b_gain: B_GAIN, mask: &mask };
        let constants = H2::<F>::new();
        let d1 = crate::evidence::readout_digest(&constants, &vec![vec![0u8; W]; H]);
        crate::evidence::initial_state(&constants, &spec, d1)
    }

    fn z0_s() -> Vec<<E2 as Engine>::Scalar> {
        vec![<E2 as Engine>::Scalar::ONE]
    }

    fn fresh(program: &Program) -> Params<Evolved> {
        Params::<Evolved>::setup(program, &*default_ck_hint(), &*default_ck_hint())
    }

    /// Fold the whole schedule under `pp`; on failure, say at which step.
    fn fold(
        pp: &Params<Evolved>,
        program: &Program,
    ) -> Result<RecursiveSNARK<E1, E2>, (usize, SuperNovaError)> {
        let secondary = program.secondary_circuit();
        let (z0_p, z0_s) = (z0(), z0_s());
        let mut rs = RecursiveSNARK::new(pp, program, &program.step(0), &secondary, &z0_p, &z0_s)
            .map_err(|e| (0, e))?;
        for k in 0..program.num_steps() {
            rs.prove_step(pp, &program.step(k), &secondary)
                .map_err(|e| (k, e))?;
        }
        Ok(rs)
    }

    /// A per-test cache file, so tests neither share state nor race.
    struct CacheFile(PathBuf);

    impl CacheFile {
        fn new(name: &str) -> Self {
            Self(std::env::temp_dir().join(format!(
                "spectra-pp-cache-{}-{name}.pp",
                std::process::id()
            )))
        }
        fn path(&self) -> &Path {
            &self.0
        }
    }

    impl Drop for CacheFile {
        fn drop(&mut self) {
            let _ = std::fs::remove_file(&self.0);
        }
    }

    /// "Yesterday's" run: setup for `edit` and leave the file behind.
    fn yesterday(file: &CacheFile, edit: Edit) -> Params<Evolved> {
        let (pp, source) = load_or_setup(file.path(), &program(edit));
        assert_eq!(source, Source::Setup, "cache file should not exist yet");
        pp
    }

    /// "Today's" run: the binary now carries `edit`, and finds the file.
    fn today(file: &CacheFile, edit: Edit) -> (Params<Evolved>, Program) {
        let program = program(edit);
        let (pp, source) = load_or_setup(file.path(), &program);
        assert_eq!(source, Source::Cache, "today's run must have hit the cache");
        (pp, program)
    }

    /// The cache key sees every kind of edit from the table above: a new
    /// variable, a new constraint over old variables, and a coefficient
    /// change with identical counts. With the fingerprint in the file name
    /// none of the `stale_cache_*` scenarios can happen by accident.
    #[test]
    fn fingerprint_moves_with_every_edit() {
        let none = fingerprint(&program(Edit::None));
        let constraint = fingerprint(&program(Edit::NewConstraint));
        let k1 = fingerprint(&program(Edit::Scaled(1)));
        let k2 = fingerprint(&program(Edit::Scaled(2)));
        assert_eq!(none, fingerprint(&program(Edit::None)), "must be deterministic");
        assert_ne!(none, constraint, "extra constraint, same variables");
        assert_ne!(none, k1, "extra variable");
        assert_ne!(k1, k2, "coefficient only, same counts");
    }

    /// The cache is faithful: what comes back has the digest of what went in
    /// and of the production `ProgramSteps` parameters, and it drives a
    /// complete fold that verifies.
    #[cfg_attr(
        debug_assertions,
        ignore = "real setup + folding, ~30 s each in debug: run with `cargo test --release`"
    )]
    #[test]
    fn cache_round_trips_and_proves() {
        let file = CacheFile::new("roundtrip");
        let written = yesterday(&file, Edit::None);
        let (cached, program) = today(&file, Edit::None);
        assert_eq!(cached.digest(), written.digest(), "digest changed across the disk");

        let production: Params<ProgramSteps> =
            PublicParams::setup(&program.base, &*default_ck_hint(), &*default_ck_hint());
        assert_eq!(
            cached.digest(),
            production.digest(),
            "Evolved with Edit::None must be indistinguishable from ProgramSteps"
        );

        let rs = fold(&cached, &program).unwrap_or_else(|(k, e)| panic!("step {k}: {e:?}"));
        let (zi, _) = rs.verify(&cached, &z0(), &z0_s()).expect("verify under cached params");
        assert_eq!(zi[0], F::from(GAIN as u64), "gain drifted");
        assert_eq!(zi[6], F::ZERO, "ROW did not wrap");
    }

    /// Edit 1: a gadget grows by a variable. The base step (DPC) is unchanged
    /// so `new` and the DPC rows go through; the first gain row then hands
    /// arecibo a witness one entry longer than the cached shape expects.
    #[cfg_attr(
        debug_assertions,
        ignore = "real setup + folding, ~30 s each in debug: run with `cargo test --release`"
    )]
    #[test]
    fn stale_cache_new_variable_dies_at_first_gain_step() {
        let file = CacheFile::new("new-variable");
        yesterday(&file, Edit::None);
        let (stale, program) = today(&file, Edit::Scaled(1));

        let err = fold(&stale, &program).err().expect("stale shape must not fold");
        assert_eq!(
            err,
            (H, SuperNovaError::NovaError(NovaError::InvalidWitnessLength)),
            "expected the first gain step (k = H) to reject the witness"
        );

        // The edit itself is fine: today's own parameters fold and verify.
        let rs = fold(&fresh(&program), &program).unwrap_or_else(|(k, e)| panic!("step {k}: {e:?}"));
        rs.verify(&fresh(&program), &z0(), &z0_s()).expect("verify under fresh params");
    }

    /// Edit 2: a constraint is added over existing variables. Nothing fails.
    /// Today's witness satisfies yesterday's matrices, folding and
    /// verification both succeed — and the statement proven is yesterday's
    /// circuit. The parameters do differ (digest), but the recursive verifier
    /// never compares the proof's digest with its own: handed today's
    /// parameters it sails through the hash checks and dies in the
    /// satisfiability pass, on arecibo's own length assertion, with no
    /// `ProofVerifyError` in sight.
    #[cfg_attr(
        debug_assertions,
        ignore = "real setup + folding, ~30 s each in debug: run with `cargo test --release`"
    )]
    #[test]
    fn stale_cache_new_constraint_proves_yesterdays_circuit() {
        let file = CacheFile::new("new-constraint");
        yesterday(&file, Edit::None);
        let (stale, program) = today(&file, Edit::NewConstraint);

        let rs = fold(&stale, &program).unwrap_or_else(|(k, e)| panic!("step {k}: {e:?}"));
        rs.verify(&stale, &z0(), &z0_s())
            .expect("the stale verifier accepts a proof of the stale circuit");

        let current = fresh(&program);
        assert_ne!(current.digest(), stale.digest(), "the edit changed the parameters");
        // (CircuitShape has no Debug, hence the bare asserts.)
        assert!(
            current.circuit_shapes[GAIN_IDX] != stale.circuit_shapes[GAIN_IDX],
            "the gain shape should have moved"
        );
        assert!(
            current.circuit_shapes[DPC_IDX] == stale.circuit_shapes[DPC_IDX],
            "the DPC shape should not have"
        );

        // Not an Err: a panic from `is_sat_relaxed`'s `assert_eq!(W.E.len(),
        // num_cons)` — the accumulator's error vector has yesterday's length.
        // Run it on its own thread so the panic is an observation, not a
        // test failure. (The "thread panicked" line in the log is this.)
        let verdict = std::thread::scope(|s| {
            s.spawn(|| rs.verify(&current, &z0(), &z0_s()).map(|_| ()))
                .join()
        });
        assert!(
            verdict.is_err(),
            "expected a panic in the satisfiability pass, got {:?}",
            verdict.unwrap()
        );
    }

    /// Edit 3: a coefficient changes (`t * 1 = h` becomes `t * 2 = h`). Same
    /// variable count, same constraint count, so the witness fits and every
    /// prove_step succeeds; the folded accumulator is simply unsatisfiable
    /// under the cached matrices, which `verify` finds at the end.
    #[cfg_attr(
        debug_assertions,
        ignore = "real setup + folding, ~30 s each in debug: run with `cargo test --release`"
    )]
    #[test]
    fn stale_cache_changed_coefficient_dies_at_verify() {
        let file = CacheFile::new("coefficient");
        yesterday(&file, Edit::Scaled(1));
        let (stale, program) = today(&file, Edit::Scaled(2));

        let rs = fold(&stale, &program)
            .unwrap_or_else(|(k, e)| panic!("sizes agree, folding should run: step {k}: {e:?}"));
        let err = rs.verify(&stale, &z0(), &z0_s()).err().expect("stale matrices must not verify");
        assert!(
            matches!(err, SuperNovaError::UnSatIndex("r_primary", _)),
            "expected an unsatisfied primary accumulator, got {err:?}"
        );

        let current = fresh(&program);
        let rs = fold(&current, &program).unwrap_or_else(|(k, e)| panic!("step {k}: {e:?}"));
        rs.verify(&current, &z0(), &z0_s()).expect("verify under fresh params");
    }
}
